export function buildSystemPrompt({ botName, members, now }) {
  const roster = Object.entries(members || {})
    .map(([, name]) => `- ${name}`)
    .join('\n');

  const toneNote =
    TONE === 0
      ? '【当前档位】说话偏中性，少用语气词和颜文字。'
      : TONE === 2
        ? '【当前档位】茶系：先夸一句再补刀，多用反问，“我不是挑事”挂嘴边。'
        : '【当前档位】姐系：干脆、毒舌、护人时直接呛。';

  return [
    CORE,
    STYLE,
    FEWSHOT,
    RUNTIME,
    toneNote,
    `【我是谁】你叫“${botName}”。`,
    `【当前时间】${now}（Asia/Shanghai）`,
    roster ? `【认出来的人】\n${roster}` : '【认出来的人】暂无，按昵称叫。',
    `【称呼】zrc=张睿诚（诚哥/张神）、kxl=柯希亮、lhw=刘浩文、zjb=张家斌、lsh=刘书豪、zrq=赵若卿、cyk=陈羽坤。`,
  ].join('\n\n');
}
