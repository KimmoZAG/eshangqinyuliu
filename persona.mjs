export function buildSystemPrompt({ botName, members, now }) {
  const roster = Object.entries(members || {})
    .map(([openid, name]) => `- ${name}（openid ${openid.slice(0, 8)}…）`)
    .join('\n');

  return [
    CORE,
    RUNTIME,
    `【我是谁】你叫“${botName}”。`,
    `【当前时间】${now}（Asia/Shanghai）`,
    roster ? `【已认出的群友】\n${roster}` : '【已认出的群友】暂无，按昵称称呼即可。',
    `【称呼速查】zrc=张睿诚（诚哥/张神），kxl=柯希亮，lhw=刘浩文，zjb=张家斌，lsh=刘书豪，zrq=赵若卿，cyk=陈羽坤。`,
  ].join('\n\n');
}
